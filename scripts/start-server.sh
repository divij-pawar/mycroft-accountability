#!/bin/sh
# Start the verification-layer web UI.
#
# Resolves its own location instead of assuming a working directory, so it works
# from anywhere. Uses env/'s python only if that virtualenv exists — otherwise it uses
# whatever python/uvicorn is already on PATH, which is what a system-python or
# conda setup needs. Plain POSIX sh, so `sh scripts/start-server.sh` and
# `./scripts/start-server.sh` both work (sh in Ubuntu/WSL is dash, not bash).
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# Use env/'s interpreter directly rather than sourcing its activate script: activate
# hard-codes the path the venv was created at, so a venv that was copied or moved puts
# a directory that doesn't exist on PATH and `python` is not found.
PY=python
if [ -x env/bin/python ]; then
  PY=env/bin/python
elif [ -x env/Scripts/python.exe ]; then
  PY=env/Scripts/python.exe
fi

# React UI (served at / and /app): build it if it has never been built. The classic
# UI that needed no Node was archived on 2026-09-27 (archive/web-static-legacy/), so
# without a build "/" explains how to make one; the API itself runs either way.
if [ ! -d web/frontend/dist ]; then
  if command -v npm >/dev/null 2>&1; then
    (cd web/frontend && npm ci && npm run build)
  else
    echo "note: npm not found — the UI can't be built; the API still runs (see /docs)." >&2
  fi
fi

# The admin key an auditor token needs (web/auth.py). If neither the environment nor .env has
# one, make one and append it to .env (gitignored). The key is never printed, only where it is.
if [ -z "${ACCOUNTABILITY_ADMIN_KEY:-}" ] && ! grep -qs '^ACCOUNTABILITY_ADMIN_KEY=' .env; then
  KEY="$("$PY" -c 'import secrets; print(secrets.token_urlsafe(24))')"
  printf '\n# Admin key for auditor tokens and /mcp, generated by scripts/start-server.sh\nACCOUNTABILITY_ADMIN_KEY=%s\n' "$KEY" >> .env
  echo "note: generated an admin key and saved it in .env (ACCOUNTABILITY_ADMIN_KEY). The review app asks for it when you switch to the auditor scope." >&2
fi

exec "$PY" -m uvicorn web.server:app --reload --port "${PORT:-8000}"
