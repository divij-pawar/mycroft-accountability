"""
Which company is a question about? A ticker for filing a chat run, from the question's words.

Added 2026-10-06. Chat runs used to be filed under the question's first word, upper-cased
("What was Apples revenue last quarter?" became ticker WHAT, run 03bd3ca5), so History
and the per-ticker views never found them under AAPL.

How a ticker is found, in order (first hit wins):
  1. `$AAPL` written anywhere, if it is a listed ticker;
  2. an all-capitals word of 2 to 5 letters that is a listed ticker ("AAPL", "MSFT"),
     except abbreviations questions use (EPS, CEO, SEC, ...);
  3. a company name, capitalised in the question as a proper noun ("Apple", "Apple's",
     "Apples", "Bank of America"): names are SEC titles without their legal suffixes
     ("Apple Inc." is "apple", "AMAZON COM INC" is "amazon"). The longest name wins; then
     the earliest in the question; then the larger company (SEC lists largest first).
Nothing found gives None, and the caller files the run as CHAT.

This is a heuristic for filing, not a fact the record rests on: a question naming two
companies is filed under one, and a company whose name is a common word is found only
when the question capitalises it. The listed tickers are a snapshot,
datasources/company_tickers.tsv (its first line says when it was fetched), regenerated by
scripts/refresh_tickers.py; nothing here touches the network. Stdlib only.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

SNAPSHOT = Path(__file__).with_name("company_tickers.tsv")

# Legal-form words dropped from the end of a title, repeatedly ("Holdings Inc", "Co Ltd").
_SUFFIXES = {
    "inc", "incorporated", "corp", "corporation", "co", "company", "companies", "ltd",
    "limited", "plc", "holdings", "holding", "group", "sa", "nv", "ag", "se", "lp", "llc",
    "the", "com", "de", "cv", "ab", "asa", "spa", "bhd", "tbk", "trust", "class", "a", "b",
}
# Capitalised words that start questions and are never meant as a company.
_NOT_A_NAME = {
    "what", "how", "who", "when", "which", "why", "where", "is", "was", "were", "are", "did",
    "does", "do", "will", "would", "can", "could", "should", "tell", "give", "show", "list",
    "compare", "find", "explain", "summarize", "summarise", "please", "the", "a", "an", "in",
    "for", "of", "and", "or", "q1", "q2", "q3", "q4", "fy", "i", "my", "our", "has", "have",
}
# All-capitals words in finance questions that also happen to be listed tickers.
_NOT_A_TICKER = {
    "A", "I", "AN", "CEO", "CFO", "COO", "CTO", "EPS", "GAAP", "US", "USA", "SEC", "AI", "IPO",
    "ETF", "FY", "YOY", "QOQ", "TTM", "EBIT", "PE", "ROE", "ROI", "ROA", "FCF", "IT", "OR",
    "AND", "THE", "FOR", "ALL", "ARE", "NOW", "ON", "SO", "BE", "GO", "UK", "EU", "CEOS",
}
_MIN_NAME_CHARS = 3
_SHORT_NAME_RANK = 500
# First words that name a kind of company, not one company.
_GENERIC_FIRST_WORDS = {
    "american", "general", "first", "united", "bank", "national", "international", "global",
    "new", "southern", "northern", "western", "eastern", "royal", "capital", "public",
    "republic", "state", "union", "china", "canadian", "british", "japan", "korea", "world",
    "energy", "health", "life", "real", "digital", "advanced", "applied", "consolidated",
    "pacific", "atlantic", "texas", "california", "florida", "federal", "standard",
    "interactive", "enterprise", "service", "us", "u", "blue", "green", "red",
}
_MAX_NAME_WORDS = 5

_WORD_RE = re.compile(r"[A-Za-z0-9&]+(?:['’][A-Za-z]+)?")


def _name_key(title: str) -> str:
    words = re.sub(r"[^a-z0-9& ]", " ", title.lower().replace("&", " & ")).split()
    while words and words[-1] in _SUFFIXES:
        words.pop()
    while words and words[0] == "the":
        words.pop(0)
    return " ".join(words)


@lru_cache(maxsize=1)
def _index() -> tuple[frozenset[str], dict[str, str]]:
    """(every listed ticker, name key -> ticker of the largest company with that name)."""
    tickers: set[str] = set()
    names: dict[str, str] = {}
    ranked: list[str] = []
    for line in SNAPSHOT.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#") or "\t" not in line:
            continue
        ticker, title = line.split("\t", 1)
        tickers.add(ticker)
        key = _name_key(title)
        if len(key) >= _MIN_NAME_CHARS and key not in _NOT_A_NAME:
            names.setdefault(key, ticker)
        ranked.append(key)
    # A large company is often called by its first word ("Ford" for FORD MOTOR CO), so the
    # first word of the _SHORT_NAME_RANK largest names is a name too, unless it's generic.
    # Added after full names, so a company whose whole name is that word keeps it.
    for key in ranked[:_SHORT_NAME_RANK]:
        first = key.split(" ")[0]
        if (" " in key and len(first) >= 4 and first not in _GENERIC_FIRST_WORDS
                and first not in _NOT_A_NAME):
            names.setdefault(first, names[key])
    return frozenset(tickers), names


def _variants(word: str) -> list[str]:
    """A question word as it might appear in a name: as written, without 's, without a plural s."""
    w = word.lower().replace("’", "'")
    out = [w]
    if w.endswith("'s"):
        out.append(w[:-2])
    elif w.endswith("s") and len(w) > _MIN_NAME_CHARS + 1:
        out.append(w[:-1])  # "Apples revenue": the possessive written without its apostrophe
    return out


def ticker_for(text: str | None) -> str | None:
    """The listed ticker `text` is most likely about, or None (see the module docstring)."""
    if not text:
        return None
    tickers, names = _index()

    for m in re.finditer(r"\$([A-Za-z]{1,5})\b", text):
        if m.group(1).upper() in tickers:
            return m.group(1).upper()

    for m in re.finditer(r"\b[A-Z]{2,5}\b", text):
        if m.group(0) in tickers and m.group(0) not in _NOT_A_TICKER:
            return m.group(0)

    words = [m.group(0) for m in _WORD_RE.finditer(text)]
    best: tuple[int, int, str] | None = None  # (-words, position, ticker)
    for i, first in enumerate(words):
        if not first[0].isupper() or first.lower().rstrip("'s’") in _NOT_A_NAME:
            continue
        for n in range(min(_MAX_NAME_WORDS, len(words) - i), 0, -1):
            span = words[i:i + n]
            # Only the last word of a name takes a possessive or plural ending.
            heads = [w.lower() for w in span[:-1]]
            for last in _variants(span[-1]):
                ticker = names.get(" ".join(heads + [last]))
                if ticker and (best is None or (-n, i) < best[:2]):
                    best = (-n, i, ticker)
            if best is not None and best[0] == -n and best[1] == i:
                break
    return best[2] if best else None
